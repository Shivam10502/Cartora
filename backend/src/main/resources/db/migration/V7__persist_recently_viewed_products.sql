CREATE TABLE recently_viewed_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    viewed_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_recent_product_user_product UNIQUE (user_id, product_id)
);

CREATE INDEX idx_recent_product_user_viewed
    ON recently_viewed_product(user_id, viewed_at DESC, id DESC);
